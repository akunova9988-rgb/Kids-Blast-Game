export function lessonReport(correct, total) {
  const percent = total ? Math.round((correct / total) * 100) : 0;
  if (percent >= 90) return { percent, mark: 5, line: 'Отлично усвоил' };
  if (percent >= 75) return { percent, mark: 4, line: 'Хорошо понял' };
  if (percent >= 50) return { percent, mark: 3, line: 'Нужно ещё потренироваться' };
  return { percent, mark: 2, line: 'Нужно повторить' };
}
